#!/usr/bin/env node
import fs from 'node:fs';
const read = (file) => fs.readFileSync(file, 'utf8');
const exists = (file) => fs.existsSync(file);
const checks = [];
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) });

const schema = read('prisma/schema.prisma');
const migration = read('prisma/migrations/20260717040000_meta_v6_phase6_privacy_governance/migration.sql');
const consentTypes = read('lib/privacy/consent-types.ts');
const resolver = read('lib/privacy/consent-resolver.ts');
const policy = read('lib/privacy/tracking-policy.ts');
const normalize = read('lib/privacy/pii-normalize.ts');
const hash = read('lib/privacy/pii-hash.ts');
const redaction = read('lib/privacy/pii-redaction.ts');
const retention = read('lib/privacy/retention-worker.ts');
const deletion = read('lib/privacy/deletion-worker.ts');
const privacyJobs = read('lib/privacy/jobs.ts');
const privacyScheduler = read('lib/privacy/scheduler.ts');
const privacyWorker = read('workers/privacy-governance.worker.ts');
const browserTypes = read('lib/meta/browser/types.ts');
const browserPayload = read('lib/meta/browser/payload.ts');
const browserClient = read('lib/meta/browser/client.ts');
const publicCapi = read('app/api/facebook-capi/route.ts');
const outboxTypes = read('lib/meta/capi/types.ts');
const outboxRepo = read('lib/meta/capi/outbox-repository.ts');
const outboxSender = read('lib/meta/capi/sender.ts');
const attribution = read('lib/tracking/order-attribution.ts');
const consentManager = read('lib/tracking/pixels/TrackingConsentManager.tsx');
const deletionRoute = read('app/data-deletion/route.ts');
const admin = read('app/api/admin/meta/privacy/route.ts');

check('TrackingConsentState enum exists', schema.includes('enum TrackingConsentState'));
check('DataDeletionRequestStatus enum exists', schema.includes('enum DataDeletionRequestStatus'));
check('TrackingConsentRecord model exists', schema.includes('model TrackingConsentRecord'));
check('DataDeletionRequest model exists', schema.includes('model DataDeletionRequest'));
check('PrivacyAuditLog model exists', schema.includes('model PrivacyAuditLog'));
check('TrackingSuppression model exists', schema.includes('model TrackingSuppression'));
check('non-essential default is false', /nonEssentialTrackingAllowed Boolean @default\(false\)/.test(schema));
check('historical consent is conservatively reset', migration.includes('HISTORICAL_CONSENT_UNVERSIONED') && migration.includes('"nonEssentialTrackingAllowed" = false'));
check('consent records require version and policy version', schema.includes('version     String') && schema.includes('policyVersion String'));
check('withdrawal timestamp exists', schema.includes('withdrawnAt DateTime?'));
check('retention timestamps exist on privacy models', (schema.match(/retentionUntil/g) ?? []).length >= 4);
check('outbox has policy metadata columns', ['policyVersion','policyReason','consentState','consentVersion','allowAdvancedMatching','retentionUntil'].every((x) => outboxTypes.includes(x) && outboxRepo.includes(x)));
check('policy version is explicit', consentTypes.includes("meta-v6-2026-07-17.1"));
check('unknown does not equal granted', resolver.includes("consentState === 'GRANTED'") && resolver.includes('Boolean(input.consentVersion?.trim())'));
check('withdrawal takes precedence', resolver.includes("state === 'WITHDRAWN'") && resolver.includes("'CONSENT_WITHDRAWN'"));
check('internal/test/bot/deletion precedence', ['internalTraffic','testTraffic','botTraffic','deletionRequested'].every((x) => resolver.includes(x)));
check('allowed user data is policy controlled', resolver.includes('allowedUserDataFields') && policy.includes('hashedUserDataFields'));
check('email normalization trims and lowercases', normalize.includes("trim().toLowerCase()"));
check('phone normalization supports Bangladesh E164-like digits', normalize.includes("startsWith('01')") && normalize.includes('`88${digits}`'));
check('no double hashing', hash.includes('isSha256Hex(normalized)'));
check('recursive operational redaction exists', redaction.includes('redactOperationalPayload') && redaction.includes('findRawPiiPaths'));
check('browser envelope contains policy decision', browserTypes.includes('policyDecision: TrackingDecision'));
check('browser builder resolves policy decision', browserPayload.includes('getMetaBrowserTrackingDecision'));
check('browser dispatch enforces pixel and CAPI decision', browserClient.includes('event.policyDecision') && browserClient.includes('allowCapiEvent'));
check('public CAPI re-resolves server policy', publicCapi.includes('resolveTrackingDecision') && publicCapi.includes('TRACKING_CONSENT_VERSION_COOKIE'));
check('public CAPI attaches policy metadata', publicCapi.includes('policyMetadata(policyDecision)') && publicCapi.includes('policyDecision,'));
check('public CAPI uses server-side PII hash helpers', publicCapi.includes('hashPiiEmail') && publicCapi.includes('hashPiiPhone'));
check('outbox sender suppresses non-granted policy', outboxSender.includes("existing.policyReason !== 'CONSENT_GRANTED'") && outboxSender.includes('markMetaOutboxSuppressed'));
check('order attribution persists version and reason', attribution.includes('trackingConsentVersion') && attribution.includes('trackingPolicyReason'));
check('consent manager persists versioned decision', consentManager.includes('/api/privacy/consent') && consentManager.includes('CURRENT_TRACKING_CONSENT_VERSION'));
check('consent API exists', exists('app/api/privacy/consent/route.ts'));
check('deletion callback creates durable request', deletionRoute.includes('createDataDeletionRequest') && deletionRoute.includes('enqueuePrivacyJob'));
check('deletion processing anonymizes and suppresses', deletion.includes('anonymizeUserDataById') && deletion.includes('DELETION_REQUESTED'));
for (const name of ['PRIVACY_RETENTION_CLEANUP','PRIVACY_DELETION_PROCESSOR','TRACKING_SUPPRESSION_SYNC','PII_AUDIT_SCAN']) {
  check(`privacy job ${name}`, privacyJobs.includes(name) && privacyWorker.includes(name));
}
check('retention cleanup is bounded and resumable', retention.includes('LIMIT $1') && retention.includes('runPrivacyRetentionCleanup'));
check('PII audit scan is persisted', retention.includes('PII_AUDIT_SCAN_COMPLETED') && retention.includes('appendPrivacyAudit'));
check('scheduler recovers deletions every 5 minutes', privacyScheduler.includes('deletion-recovery-5m'));
check('scheduler includes suppression, retention and PII scan', ['suppression-sync-15m','retention-hourly','pii-audit-daily'].every((x) => privacyScheduler.includes(x)));
check('privacy worker has stalled recovery', privacyWorker.includes('maxStalledCount: 2'));
check('SUPER_ADMIN governance API exists', admin.includes('requireSuperAdmin') && admin.includes('consentDistribution') && admin.includes('suppressedEventCount'));
check('deletion status API exists', exists('app/api/privacy/deletion/status/[code]/route.ts'));
check('package exposes Phase 6 gate', read('package.json').includes('qa:meta-v6-phase6'));

const passed = checks.filter((item) => item.ok).length;
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'} ${item.label}`);
console.log(`\nMeta v6 Phase 6 audit: ${passed}/${checks.length} passed`);
if (passed !== checks.length) process.exit(1);
