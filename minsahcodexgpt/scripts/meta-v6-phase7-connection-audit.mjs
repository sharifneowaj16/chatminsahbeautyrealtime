#!/usr/bin/env node
import fs from 'node:fs';
const read = (file) => fs.readFileSync(file, 'utf8');
const exists = (file) => fs.existsSync(file);
const checks = [];
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) });
const has = (file, ...tokens) => exists(file) && tokens.every((token) => read(file).includes(token));

const schema = read('prisma/schema.prisma');
const migration = read('prisma/migrations/20260717050000_meta_v6_phase7_connection_health/migration.sql');
const client = read('lib/meta/connection/client.ts');
const centralGraphClient = read('lib/meta-platform/transports/graph-http/client.ts');
const debug = read('lib/meta/connection/token-debug.ts');
const centralDebug = read('lib/meta-platform/transports/graph-http/token-debug.ts');
const permissions = read('lib/meta/connection/permissions.ts');
const assets = read('lib/meta/connection/assets.ts');
const version = read('lib/meta/connection/version-policy.ts');
const centralVersion = read('lib/meta-platform/versioning/registry.ts');
const readiness = read('lib/meta/connection/readiness.ts');
const repo = read('lib/meta/connection/repository.ts');
const jobs = read('lib/jobs/job-types.ts');
const queues = read('lib/jobs/queues.ts');
const scheduler = read('lib/jobs/scheduler.ts');
const worker = read('workers/meta-token-health.worker.ts');
const route = read('app/api/admin/meta/connection/route.ts');
const admin = read('app/admin/meta-business/page.tsx');
const env = read('.env.example');
const packageJson = JSON.parse(read('package.json'));

check('connection status enum exists', schema.includes('enum MetaConnectionStatus'));
check('connection model exists', schema.includes('model MetaConnection'));
check('connection check history exists', schema.includes('model MetaConnectionCheck'));
check('API version policy model exists', schema.includes('model MetaApiVersionPolicy'));
check('regression status enum exists', schema.includes('enum MetaVersionRegressionStatus'));
check('connection status index exists', schema.includes('@@index([status])'));
check('token expiry index exists', schema.includes('@@index([tokenExpiresAt])'));
check('forward migration creates status enum', migration.includes('CREATE TYPE "MetaConnectionStatus"'));
check('forward migration creates connection tables', migration.includes('CREATE TABLE "MetaConnection"') && migration.includes('CREATE TABLE "MetaConnectionCheck"'));
check('forward migration seeds version policy', migration.includes('meta-api-v24-policy') && migration.includes('meta-api-v25-policy'));
check('official TBD is not replaced by fabricated expiry', migration.includes('without inventing an official expiration date') && migration.includes("'v25.0'"));
check('appsecret proof module exists', has('lib/meta/connection/appsecret-proof.ts', 'createHmac', "'sha256'"));
check('Graph client sends bearer header', centralGraphClient.includes('Authorization: `Bearer ${credential.readAccessToken()}`'));
check('Graph client adds appsecret_proof', centralGraphClient.includes('query.appsecret_proof = buildMetaAppSecretProof'));
check('Graph client has timeout', centralGraphClient.includes('AbortController') && centralGraphClient.includes('META_GRAPH_TIMEOUT'));
check('legacy Graph client delegates to central compatibility boundary', client.includes('createLegacyMetaGraphClient'));
check('Graph errors are safely classified', has('lib/meta/connection/errors.ts', 'redactMetaSecrets', 'safeMetaConnectionError'));
check('token debug uses debug_token', centralDebug.includes("path: 'debug_token'"));
check('legacy token debug delegates to central transport', debug.includes('debugMetaGraphAccessToken'));
check('token app association is checked', debug.includes('META_TOKEN_APP_MISMATCH') && debug.includes('appIdMatches'));
check('token value is not part of result type', !read('lib/meta/connection/types.ts').includes('accessToken:'));
check('permissions are verified through API', permissions.includes("'/me/permissions'"));
check('missing permissions are explicit', permissions.includes('missing'));
check('business asset is API verified', assets.includes("key: 'business'"));
check('catalog asset is API verified', assets.includes("key: 'catalog'"));
check('dataset/pixel assets are API verified', assets.includes("key: 'dataset'") && assets.includes("key: 'pixel'"));
check('page asset uses page token where configured', assets.includes("key: 'page'") && assets.includes('pageAccessToken'));
check('ad account is API verified', assets.includes("key: 'adAccount'"));
check('Instagram asset is API verified', assets.includes("key: 'instagramAccount'"));
check('asset ID mismatch fails closed', assets.includes('META_ASSET_ID_MISMATCH'));
check('version policy is file backed', version.includes('config/meta-api-version-policy.json') && centralVersion.includes('config/meta-api-version-policy.json'));
check('minimum version is enforced', centralVersion.includes('GRAPH_API_VERSION_BELOW_MINIMUM'));
check('internal block date is enforced', centralVersion.includes('INTERNAL_VERSION_MIGRATION_DEADLINE_REACHED'));
check('target regression pending is visible', centralVersion.includes('TARGET_VERSION_REGRESSION_PENDING'));
check('readiness aggregates invalid token', readiness.includes("return 'INVALID_TOKEN'"));
check('readiness aggregates missing permission', readiness.includes("return 'MISSING_PERMISSION'"));
check('readiness aggregates asset not found', readiness.includes("return 'ASSET_NOT_FOUND'"));
check('readiness persists checks', readiness.includes('persistMetaConnectionReadiness'));
check('repository stores safe JSON snapshots', repo.includes('MetaConnectionCheck') && repo.includes('JSON.stringify(readiness.permissions)'));
check('job payload has scoped health checks', jobs.includes("checks: Array<'TOKEN' | 'PERMISSIONS' | 'ASSETS' | 'VERSION'>"));
check('job validator forbids secrets', jobs.includes('SECRET_IN_JOB_PAYLOAD'));
check('queue producer does not accept token values', !/enqueueMetaConnectionHealthJob[\s\S]{0,500}accessToken/.test(queues));
check('daily token/permission/asset schedule exists', scheduler.includes('token-permission-asset-daily'));
check('weekly API version schedule exists', scheduler.includes('api-version-weekly'));
check('worker runs canonical readiness', worker.includes('checkMetaConnectionReadiness'));
check('admin connection API requires SUPER_ADMIN recheck', route.includes('requireSuperAdmin') && route.includes("action must be recheck"));
check('admin API declares no-token secret policy', route.includes('accessTokenReturned: false') && route.includes('appSecretReturned: false'));
check('admin console displays connection state and recheck', admin.includes('Connection, token & API version health') && admin.includes('/api/admin/meta/connection'));
check('environment documents app ID and secret reference', env.includes('META_APP_ID=') && env.includes('META_ACCESS_TOKEN_SECRET_REF='));
check('environment documents required permissions', env.includes('META_REQUIRED_PERMISSIONS='));
check('Business SDK dependency is exact', /^\d+\.\d+\.\d+$/.test(packageJson.dependencies['facebook-nodejs-business-sdk'] ?? ''));
check('version CI audit exists', exists('scripts/meta-graph-version-policy-audit.mjs'));

const failed = checks.filter((item) => !item.ok);
console.log(`Meta v6 Phase 7 connection audit: ${checks.length - failed.length}/${checks.length} passed`);
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'} ${item.label}`);
if (failed.length) process.exit(1);
