#!/usr/bin/env node
import fs from 'node:fs';
const read = (file) => fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
const exists = (file) => fs.existsSync(file);
const checks = [];
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) });
const has = (file, ...tokens) => exists(file) && tokens.every((token) => read(file).includes(token));

const schema = read('prisma/schema.prisma');
const migration = read('prisma/migrations/20260717060000_meta_v6_phase8_lead_crm/migration.sql');
const route = read('app/api/webhooks/meta/route.ts');
const signature = read('lib/meta/leads/signature.ts');
const sharedSignature = read('lib/meta-platform/transports/webhook/signature.ts');
const sharedRouteHandler = read('lib/meta-platform/transports/webhook/route-handler.ts');
const sharedParser = read('lib/meta-platform/transports/webhook/parser.ts');
const leadHandoff = read('lib/meta/leads/handoff.ts');
const verify = read('lib/meta/leads/verify.ts');
const receipt = read('lib/meta/leads/receipt.ts');
const fetcher = read('lib/meta/leads/fetch.ts');
const normalize = read('lib/meta/leads/normalize.ts');
const dedupe = read('lib/meta/leads/deduplicate.ts');
const assign = read('lib/meta/leads/assign.ts');
const lifecycle = read('lib/meta/leads/lifecycle.ts');
const repository = read('lib/meta/leads/repository.ts');
const service = read('lib/meta/leads/service.ts');
const jobs = read('lib/jobs/job-types.ts');
const queues = read('lib/jobs/queues.ts');
const scheduler = read('lib/jobs/scheduler.ts');
const worker = read('workers/meta-lead.worker.ts');
const adminList = read('app/api/admin/meta/leads/route.ts');
const adminDetail = read('app/api/admin/meta/leads/[leadId]/route.ts');
const adminFailures = read('app/api/admin/meta/webhooks/leads/route.ts');
const adminUi = read('app/admin/meta-business/leads/page.tsx');
const env = read('.env.example');

check('Meta lead lifecycle enum exists', schema.includes('enum MetaLeadStatus'));
check('Meta webhook processing enum exists', schema.includes('enum MetaWebhookProcessingStatus'));
check('Meta lead retrieval enum exists', schema.includes('enum MetaLeadRetrievalStatus'));
check('webhook receipt model exists', schema.includes('model MetaWebhookReceipt'));
check('webhook event key is unique', /eventKey\s+String\s+@unique/.test(schema));
check('leadgen ID is unique', /leadgenId\s+String\s+@unique/.test(schema));
check('lead status uses enum', /status\s+MetaLeadStatus\s+@default\(NEW\)/.test(schema));
check('lead retrieval status uses enum', schema.includes('retrievalStatus       MetaLeadRetrievalStatus'));
check('dedupe history model exists', schema.includes('model MetaLeadDuplicate'));
check('duplicate source lead is unique', /sourceLeadgenId\s+String\s+@unique/.test(schema));
check('contact attempt model exists', schema.includes('model MetaLeadContactAttempt'));
check('assignment rule model exists', schema.includes('model MetaLeadAssignmentRule'));
check('agent capacity profile exists', schema.includes('model MetaLeadAgentProfile'));
check('lead-to-order relation exists', schema.includes('@relation("MetaLeadConvertedOrder"'));
const productModel = schema.match(/model Product \{[\s\S]*?\n\}/)?.[0] ?? '';
check('lead relations are owned by AdminUser, not Product', !/assignedMetaLeads|metaLeadAgentProfile/.test(productModel));
check('forward migration creates enums', migration.includes('CREATE TYPE "MetaLeadStatus"') && migration.includes('CREATE TYPE "MetaWebhookProcessingStatus"'));
check('migration preserves existing lead rows', migration.includes('Existing lead rows are preserved'));
check('migration removes legacy raw JSON PII', migration.includes('Legacy raw JSON may contain PII') && migration.includes('DROP COLUMN "legacyRawPayload"'));
check('webhook GET verification exists', route.includes('verifyMetaWebhookChallengeRequest'));
check('webhook POST signature verification exists', route.includes('readAndVerifyMetaWebhookRequest') && sharedRouteHandler.includes('verifyMetaWebhookSignature'));
check('signature uses HMAC SHA-256', signature.includes("createHmac('sha256'") || sharedSignature.includes("createHmac('sha256'"));
check('signature comparison is timing-safe', signature.includes('timingSafeEqual') || sharedSignature.includes('timingSafeEqual'));
check('payload size limit is enforced', route.includes('META_LEAD_WEBHOOK_MAX_BYTES') && sharedRouteHandler.includes('PAYLOAD_TOO_LARGE') && sharedRouteHandler.includes('Buffer.byteLength'));
check('expected page object is required', sharedParser.includes('objectType') && verify.includes("event.routingTarget !== 'LEAD_ADS'"));
check('leadgen ID is required', verify.includes('LEADGEN_ID_REQUIRED'));
check('Page ownership is checked', verify.includes('PAGE_OWNERSHIP_MISMATCH'));
check('form ownership allowlist is checked', verify.includes('FORM_OWNERSHIP_MISMATCH'));
check('event key is deterministic', verify.includes("update(`${input.pageId}:${input.leadgenId}`)"));
check('receipt is stored before queue enqueue', leadHandoff.indexOf('const stored = await createVerifiedMetaWebhookReceipt') > -1 && leadHandoff.indexOf('const stored = await createVerifiedMetaWebhookReceipt') < leadHandoff.indexOf('await enqueueMetaLeadFetchJob'));
check('valid webhook returns fast 200', route.includes('status: 200'));
check('Redis failure leaves durable recovery path', leadHandoff.includes("disposition: 'DEFERRED'") && leadHandoff.includes("code: 'QUEUE_HANDOFF_FAILED'") && leadHandoff.includes("status: 'FAILED'"));
check('webhook raw payload is AES-GCM encrypted', has('lib/meta/leads/crypto.ts', 'aes-256-gcm', 'getAuthTag'));
check('production encryption key is required', has('lib/meta/leads/config.ts', 'META_LEAD_DATA_KEY_REQUIRED', "NODE_ENV !== 'production'"));
check('Graph lead retrieval is asynchronous', worker.includes('processMetaLeadReceipt') && queues.includes('enqueueMetaLeadFetchJob'));
check('Graph request includes full attribution fields', ['campaign_id','adset_id','ad_id','form_id','field_data'].every((token) => fetcher.includes(token)));
check('retrieved lead ID is verified', fetcher.includes('META_LEAD_ID_MISMATCH'));
check('retrieval freshness is validated', fetcher.includes('META_LEAD_TOO_OLD') && fetcher.includes('META_LEAD_CREATED_IN_FUTURE'));
check('deleted/missing lead is permanent', fetcher.includes('META_LEAD_NOT_FOUND') && fetcher.includes('permanent: true'));
check('token error has explicit state', fetcher.includes('META_LEAD_TOKEN_ERROR') && fetcher.includes("retrievalStatus: 'TOKEN_ERROR'"));
check('phone normalization supports Bangladesh E.164', normalize.includes("defaultCountryCode = '880'") && normalize.includes('`+${digits}`'));
check('email normalization lowercases', normalize.includes('.toLowerCase()'));
check('identity hashes are SHA-256', normalize.includes("createHash('sha256')"));
check('admin-facing phone and email are masked', normalize.includes('maskMetaLeadPhone') && normalize.includes('maskMetaLeadEmail'));
check('dedupe priority begins with leadgen ID', dedupe.indexOf('byLeadgen') < dedupe.indexOf('byPhone'));
check('phone dedupe precedes email', dedupe.indexOf('byPhone') < dedupe.indexOf('byEmail'));
check('assignment supports campaign/form/city/area/product interest', ['campaignId','formId','city','area','productInterest'].every((token) => assign.includes(token)));
check('assignment enforces agent capacity', assign.includes('maxOpenLeads > agent.openLeads'));
check('round-robin uses last assignment', assign.includes('lastAssignedAt'));
check('conversion requires explicit order', lifecycle.includes('META_LEAD_CONVERTED_ORDER_REQUIRED'));
check('converted order existence is verified', repository.includes('META_LEAD_CONVERTED_ORDER_NOT_FOUND'));
check('contact attempts are persisted', repository.includes('INSERT INTO "MetaLeadContactAttempt"'));
const safeListSection = repository.slice(repository.indexOf('export async function listMetaLeadsSafe'), repository.indexOf('export async function getMetaLeadSafe'));
check('safe lead list excludes raw payload columns', !safeListSection.includes('rawPayloadEncrypted') && !safeListSection.includes('normalizedData'));
check('normalized CRM metadata excludes raw phone/email values', repository.includes('safeNormalizedMetadata') && !repository.includes('JSON.stringify(input.normalized)'));
check('queue payload requires receipt ID', jobs.includes('receiptId: string') && jobs.includes('WEBHOOK_RECEIPT_ID_REQUIRED'));
check('queue payload forbids raw PII', jobs.includes("'email','phone','field_data','normalizeddata','rawpayload'"));
check('lead receipt recovery job exists', jobs.includes('LEAD_RECEIPT_RECOVERY') && worker.includes('runMetaLeadReceiptRecovery'));
check('lead SLA alert job exists', jobs.includes('LEAD_SLA_ALERT') && worker.includes('runMetaLeadSlaAlerts'));
check('lead retention job exists', jobs.includes('LEAD_RETENTION') && worker.includes('runMetaLeadRetention'));
check('5-minute receipt recovery schedule exists', scheduler.includes('lead-receipt-recovery-5m'));
check('5-minute SLA schedule exists', scheduler.includes('lead-sla-alert-5m'));
check('daily lead retention schedule exists', scheduler.includes('lead-retention-daily'));
check('manual form sync is queued, not run in request', adminList.includes('enqueueMetaLeadFormSyncJob') && adminList.includes('status: 202') && !adminList.includes('fetchFormLeads'));
check('admin lifecycle mutation is SUPER_ADMIN protected', adminDetail.includes('requireSuperAdmin'));
check('webhook failure API is authenticated', adminFailures.includes('getVerifiedAdmin'));
check('lead CRM UI shows pipeline and failures', adminUi.includes('Meta Lead Ads CRM') && adminUi.includes('Webhook failures'));
check('environment documents dedicated lead data key', env.includes('META_LEAD_DATA_KEY='));
check('environment documents form allowlist and retention', env.includes('META_LEAD_ALLOWED_FORM_IDS=') && env.includes('META_LEAD_RETENTION_DAYS='));
check('Phase 8 evidence target exists in manifest', read('docs/release/meta-v6/phase-dashboard.json').includes('phase-08-evidence.md'));

const failed = checks.filter((item) => !item.ok);
console.log(`Meta v6 Phase 8 Lead Ads/CRM audit: ${checks.length - failed.length}/${checks.length} passed`);
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'} ${item.label}`);
if (failed.length) process.exit(1);
