#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const readJson = (path) => JSON.parse(readFileSync(resolve(root, path), 'utf8'));
const write = (path, content) => writeFileSync(resolve(root, path), `${content.trim()}\n`);

const state = readJson('.ai/project-state.json');
const progress = readJson('.ai/layer-progress.json');
const execution = readJson('.ai/phase31-execution-manifest.json');
const currentId = String(state.next_item?.id ?? progress.current_item ?? '');
const activeLayerId = String(currentId.split('.')[0]);
const layer = execution.layers?.[activeLayerId];
const item = layer?.items?.find((entry) => entry.id === currentId);

if (!layer || !item) {
  console.error(`Cannot sync context: execution manifest has no item ${currentId}`);
  process.exit(1);
}
if (Number(progress.layer) !== Number(activeLayerId) || progress.current_item !== currentId) {
  console.error(`Cannot sync context: layer-progress (${progress.layer}/${progress.current_item}) disagrees with project-state (${activeLayerId}/${currentId})`);
  process.exit(1);
}

execution.current_layer = Number(activeLayerId);
execution.current_item = currentId;
write('.ai/phase31-execution-manifest.json', JSON.stringify(execution, null, 2));

const outputs = item.required_outputs.map((path) => `- \`${path}\``).join('\n');
const paths = item.primary_paths.map((path) => `- \`${path}\``).join('\n');
const criteria = item.acceptance_criteria.map((entry) => `- ${entry}`).join('\n');
const progressRows = progress.items.map((entry) => `| ${entry.id} | ${entry.title} | \`${entry.status}\` |`).join('\n');
const layerArtifacts = layer.artifacts.map((path) => `- \`${path}\``).join('\n');
const implementationLog = state.checkpoint?.implementation_verification_log ?? state.checkpoint?.verification_log;

write('AI_CONTEXT.md', `
# AI_CONTEXT.md — Minsah Beauty Live Project Context

> Generated by \`npm run ai:sync-context\`. Update machine state, then regenerate; do not hand-maintain checkpoint prose.

## Verified current checkpoint

| Field | Current value |
|---|---|
| Active phase | Phase 31 |
| Phase status | \`${state.project.phase_status}\` |
| Completed through | **${state.checkpoint.completed_through}** |
| Active layer | **Layer ${activeLayerId} — ${layer.title}** |
| Current item | **${item.id} — ${item.title}** |
| Latest working archive | \`${state.checkpoint.verified_archive}\` |
| Implementation evidence | \`${implementationLog}\` |
| Full Phase 31 complete | **No** |

## Fast execution

Run \`npm run ai:fast-start\` once, then use \`npm run ai:work-packet\` instead of repeatedly rereading the full roadmap. Work remains sequential and evidence-gated; packaging remains per completed layer.

## Current item boundary

${item.objective}

Schema change expected: **${item.schema_change_expected ? 'YES' : 'NO'}**. A schema change is allowed only with exact source evidence and a matching migration/recovery pair.
`);

write('CURRENT_TASK.md', `
# CURRENT_TASK.md — Phase 31 Layer ${item.id}

> Generated by \`npm run ai:sync-context\` from machine-readable state and the execution manifest.

\`\`\`yaml
active_phase: 31
active_layer: ${activeLayerId}
active_item: "${item.id}"
title: "${item.title.replaceAll('"', '\\"')}"
mode: ${item.mode}
status: ${progress.items.find((entry) => entry.id === item.id)?.status ?? 'NOT_STARTED'}
previous_checkpoint: "${state.checkpoint.completed_through}"
execution_mode: SEQUENTIAL_ITEM_GATE
same_session_next_item_allowed_after_gate: true
package_frequency: PER_COMPLETED_LAYER
schema_change_expected: ${item.schema_change_expected}
\`\`\`

## Objective

${item.objective}

## Primary paths

${paths}

## Acceptance criteria

${criteria}

## Required item outputs

${outputs}

## Focused command contract

\`\`\`bash
npm run ${item.command_contract.test}
npm run ${item.command_contract.audit}
npm run ${item.command_contract.gate}
\`\`\`

Do **not** create a Layer ${item.id} ZIP. After truthful evidence exists, advance with the fail-closed checkpoint helper documented in \`.ai/FAST_WORKFLOW.md\`.
`);

write('CURRENT_LAYER.md', `
# CURRENT_LAYER.md — Phase 31 Layer ${activeLayerId}

> Generated by \`npm run ai:sync-context\`.

\`\`\`yaml
active_phase: 31
active_layer: ${activeLayerId}
layer_title: "${layer.title}"
layer_status: ${progress.status}
completed_previous_checkpoint: "${state.checkpoint.completed_through}"
current_item: "${currentId}"
execution_policy: SEQUENTIAL_ITEM_GATES
same_session_continuation_allowed: true
package_frequency: PER_COMPLETED_LAYER
\`\`\`

## Layer objective

${layer.objective}

## Progress board

| Item | Scope | Status |
|---|---|---|
${progressRows}

## Item gate contract

Each numbered item requires its implementation/audit output, exact gate log, concise item result, schema/migration status and checkpoint advancement. No item ZIP is required.

## Layer artifact contract

Create these only after the final item gate passes:

${layerArtifacts}
`);

write('memory.md', `
# memory.md — Active operational memory

> Generated checkpoint block. Keep detailed historical evidence in the evidence tree, not in this file.

## Verified checkpoint

\`\`\`yaml
active_phase: 31
phase_status: ${state.project.phase_status}
completed_through: "${state.checkpoint.completed_through}"
active_layer: ${activeLayerId}
current_item: "${item.id} — ${item.title}"
verified_archive: "${state.checkpoint.verified_archive}"
checkpoint_evidence: "${state.checkpoint.verification_log}"
implementation_evidence: "${implementationLog}"
runtime_provider_evidence: ${state.checkpoint.runtime_provider_evidence}
\`\`\`

## Current task

${item.objective}

## Exact next action

Run \`npm run ai:fast-start\`, implement and verify Item ${item.id}, create its standardized result/log, then use the checkpoint helper. No item ZIP is created.

## Known blockers

${state.known_blockers.map((entry) => `- ${entry}`).join('\n')}
`);

const phasesPath = resolve(root, 'phases.md');
let phases = readFileSync(phasesPath, 'utf8');
const replacement = `**Status:** \`${state.project.phase_status}\` — ${state.checkpoint.completed_through} is verified. Latest working archive: \`${state.checkpoint.verified_archive}\`; implementation evidence: \`${implementationLog}\`. **Active Layer: ${activeLayerId}. Exact current item: ${item.id} — ${item.title}.** No full build/lint/database/Redis/realtime/live-provider PASS is claimed unless separately executed.`;
const phase31Pattern = /(## Phase 31 —[^\n]+\n\n)\*\*Status:\*\*[^\n]*/;
if (!phase31Pattern.test(phases)) {
  console.error('Cannot sync phases.md: Phase 31 status line was not found');
  process.exit(1);
}
phases = phases.replace(phase31Pattern, `$1${replacement}`);
writeFileSync(phasesPath, phases);


function replaceCheckpointSurface(path, pattern, replacement) {
  const absolute = resolve(root, path);
  const current = readFileSync(absolute, 'utf8');
  if (!pattern.test(current)) {
    console.error(`Cannot sync ${path}: checkpoint marker was not found`);
    process.exit(1);
  }
  writeFileSync(absolute, current.replace(pattern, replacement));
}

replaceCheckpointSurface('AGENTS.md', /^Current item: .*$/m, `Current item: ${item.id} — ${item.title}`);
replaceCheckpointSurface('SECOND_BRAIN.md', /^Current item: .*$/m, `Current item: ${item.id} — ${item.title}`);
replaceCheckpointSurface('.ai/prompts/start-session.md', /exact current item is \*\*[^*]+\*\*/, `exact current item is **${item.id} — ${item.title}**`);
for (const path of ['ChatGPT.md','CLAUDE.md','GEMINI.md','CODEX.md','.github/copilot-instructions.md']) {
  replaceCheckpointSurface(path, /Current item: \*\*[^*]+\*\*/, `Current item: **${item.id} — ${item.title}**`);
}
replaceCheckpointSurface('.cursor/rules/project-context.mdc', /current item is [^.]+\./i, `current item is ${item.id} — ${item.title}.`);

console.log(`Synced AI context for Phase 31 Item ${item.id}.`);
